// Insights -> Vibration analysis -> Live simulation.
// A SIMULATED engine accelerometer streamed over WebSocket /api/vibration/live (autopulse/vibstream.py).
// `source="vehicle"` (split dashboard) analyses the paired vehicle's vibration instead of the simulator.
import { memo, useCallback, useEffect, useReducer, useRef, useState } from 'react';
import { Pause, Play, RotateCcw, Square } from 'lucide-react';
import { useApi } from '../api.js';
import LineChart from '../components/charts/LineChart.jsx';
import Heatmap from '../components/charts/Heatmap.jsx';
import { HBars } from '../components/charts/Bars.jsx';
import { Stat } from '../components/ui.jsx';
import { Classification, hz, hzTick, num } from './VibrationAnalysis.jsx';
import { initialStream, reduceStream } from '../vibStreamState.js';

const COLORS = { accel_x: 'var(--s1)', accel_y: 'var(--s2)', accel_z: 'var(--s3)', vibration: 'var(--s1)' };
const DEFAULTS = { fault: 'healthy', severity: 0.8, rpm: 1500, condition: 'warm', fs: 4000, speed: 1, window_s: 4, seed: 0, envelope: false };
const LIVE_KEYS = ['fault', 'severity', 'rpm', 'condition', 'speed'];

function useVibrationStream() {
  const [s, dispatch] = useReducer(reduceStream, initialStream);
  const [connected, setConnected] = useState(false);
  const ws = useRef(null);
  useEffect(() => {
    let closed = false, retry;
    const open = () => {
      const sock = new WebSocket(`${location.protocol === 'https:' ? 'wss' : 'ws'}://${location.host}/api/vibration/live`);
      ws.current = sock;
      sock.onopen = () => setConnected(true);
      sock.onmessage = (e) => dispatch(JSON.parse(e.data));
      sock.onclose = () => { setConnected(false); if (!closed) retry = setTimeout(open, 1500); };
    };
    open();
    return () => { closed = true; clearTimeout(retry); ws.current?.close(); };   // server cancels its run on disconnect
  }, []);
  const send = useCallback((m) => ws.current?.readyState === 1 && ws.current.send(JSON.stringify(m)), []);
  return { ...s, connected, send };
}

export default function VibrationLive({ source = 'simulator' }) {
  const { state, wave, ana, error, connected, send } = useVibrationStream();
  const { data: meta } = useApi('/meta');
  const [cfg, setCfg] = useState(DEFAULTS);
  const [fdiv, setFdiv] = useState(1);
  const st = state?.state || 'idle';
  const running = st === 'running', paused = st === 'paused', active = running || paused;
  const isVehicle = source === 'vehicle';

  const change = (k, v) => {
    setCfg((c) => ({ ...c, [k]: v }));
    if (active && LIVE_KEYS.includes(k)) send({ cmd: 'update', settings: { [k]: v } });
  };
  const start = () => send({ cmd: 'start', source, settings: cfg });
  const channels = Object.keys(wave);
  const channel = state?.channel || channels[0];
  const faults = meta?.engine_faults || [{ id: 'healthy', label: 'Healthy' }];

  return (
    <div className="stack">
      <div className="vib-warn" role="status">
        <b>{isVehicle ? 'Simulated vehicle signal' : 'SIMULATED signal'}</b> — {isVehicle
          ? "the paired vehicle laptop's engine simulator, not hardware data."
          : 'generated by the AutoPulse engine simulator, not measured on a real engine or read from a sensor.'}
        {' '}Axes are seeded projections of one simulated source signal; units are g by assumption.
      </div>

      <div className="panel panel-pad stack">
        <div className="row" style={{ flexWrap: 'wrap' }}>
          <span className="eyebrow">Simulation control</span>
          <span className="chip" style={{ height: 'auto', padding: '2px 10px' }}>{connected ? STATUS_TEXT[st] : 'Connecting to API…'}</span>
          <span className="note">{state ? `elapsed ${state.elapsed_s.toFixed(1)} s · ${state.samples.toLocaleString()} samples` : ''}</span>
          <span className="spacer" />
          <button className="btn primary" disabled={!connected || active} onClick={start}><Play size={14} />{st === 'stopped' ? 'Start new run' : 'Start'}</button>
          <button className="btn" disabled={!running} onClick={() => send({ cmd: 'pause' })}><Pause size={14} />Pause</button>
          <button className="btn" disabled={!paused} onClick={() => send({ cmd: 'resume' })}><Play size={14} />Resume</button>
          <button className="btn" disabled={!active} onClick={() => send({ cmd: 'stop' })}><Square size={14} />Stop</button>
          <button className="btn ghost" disabled={!connected || st === 'idle'} onClick={() => send({ cmd: 'reset' })}><RotateCcw size={14} />Reset</button>
        </div>
        {!isVehicle && (
          <div className="vib-form">
            <label className="field">Simulated fault (ground truth)
              <select value={cfg.fault} onChange={(e) => change('fault', e.target.value)}>
                {faults.map((f) => <option key={f.id} value={f.id}>{f.label}</option>)}
              </select>
            </label>
            <label className="field">Fault severity <span className="val">{cfg.severity.toFixed(2)}</span>
              <input type="range" min="0" max="1" step="0.05" value={cfg.severity} onChange={(e) => change('severity', Number(e.target.value))} />
            </label>
            <label className="field">Engine RPM <span className="val">{cfg.rpm}</span>
              <input type="range" min="600" max="6000" step="50" value={cfg.rpm} onChange={(e) => change('rpm', Number(e.target.value))} />
            </label>
            <label className="field">Operating condition
              <select value={cfg.condition} onChange={(e) => change('condition', e.target.value)}>
                <option value="warm">Warm engine</option><option value="cold">Cold start</option>
              </select>
            </label>
            <label className="field">Sampling frequency
              <select value={cfg.fs} disabled={active} onChange={(e) => change('fs', Number(e.target.value))}>
                {[2000, 4000, 8000, 12000, 24000].map((v) => <option key={v} value={v}>{v / 1000} kHz</option>)}
              </select>
            </label>
            <label className="field">Simulation speed
              <select value={cfg.speed} onChange={(e) => change('speed', Number(e.target.value))}>
                {[0.5, 1, 2, 4].map((v) => <option key={v} value={v}>{v}× real time</option>)}
              </select>
            </label>
            <label className="field">Rolling window
              <select value={cfg.window_s} disabled={active} onChange={(e) => change('window_s', Number(e.target.value))}>
                {[2, 4, 8].map((v) => <option key={v} value={v}>{v} s</option>)}
              </select>
            </label>
            <label className="field">Random seed
              <input type="number" value={cfg.seed} disabled={active} onChange={(e) => change('seed', Math.trunc(Number(e.target.value)))} />
            </label>
          </div>
        )}
        {!isVehicle && <label className="vib-axes"><input type="checkbox" checked={cfg.envelope} disabled={active} onChange={(e) => change('envelope', e.target.checked)} />Compute envelope spectrum</label>}
        {isVehicle && <div className="note">Analyses the 1 s, 24 kHz vibration windows streamed by the paired vehicle (turn its ignition on). Mono channel; no ground truth is sent by the vehicle.</div>}
        {error && <div className="vib-error" role="alert">{error}</div>}
      </div>

      {st === 'idle' && !ana && <div className="muted">Press Start to stream a simulated engine accelerometer.</div>}

      {channels.length > 0 && (
        <div className="grid2 vib-grid" style={{ gridTemplateColumns: '1.6fr 1fr', alignItems: 'start' }}>
          <div className="stack">
            <div className="panel panel-pad">
              <div className="row" style={{ marginBottom: 8 }}>
                <span className="eyebrow">Acceleration · last {state?.settings?.window_s ?? 4} s (simulated)</span>
                <span className="spacer" />
                {channels.length > 1 && (
                  <select aria-label="Analysed axis" style={{ width: 'auto' }} value={channel} onChange={(e) => send({ cmd: 'channel', channel: e.target.value })}>
                    {channels.map((c) => <option key={c} value={c}>{c} (spectrum)</option>)}
                  </select>
                )}
              </div>
              <Waveform wave={wave} window_s={state?.settings?.window_s ?? 4} />
              <div className="chart-caption">Display points are peak-decimated; features and spectra use every sample in the window.</div>
            </div>
            {ana && (
              <div className="panel panel-pad">
                <div className="row" style={{ marginBottom: 8 }}>
                  <span className="eyebrow">Spectrum (FFT) · {ana.detail_channel}</span><span className="spacer" />
                  <select aria-label="Frequency range" style={{ width: 'auto' }} value={fdiv} onChange={(e) => setFdiv(Number(e.target.value))}>
                    {[1, 2, 4, 8, 16].map((d) => <option key={d} value={d}>0–{hz(ana.spectrogram.sampling_rate_hz / 2 / d)} Hz</option>)}
                  </select>
                </div>
                <Spectrum ana={ana} fmax={ana.spectrogram.sampling_rate_hz / 2 / fdiv} />
                <div className="eyebrow" style={{ margin: '14px 0 6px' }}>Spectrogram (STFT)</div>
                <Gram ana={ana} fmax={ana.spectrogram.sampling_rate_hz / 2 / fdiv} />
                <div className="chart-caption">FFT: Hann window over the rolling window, resolution {num(ana.settings.frequency_resolution_hz)} Hz. STFT: {ana.spectrogram.nperseg} samples, 50% overlap, dB.</div>
              </div>
            )}
          </div>
          {ana && <Side ana={ana} state={state} />}
        </div>
      )}
    </div>
  );
}

const STATUS_TEXT = { idle: 'Idle', running: 'Running', paused: 'Paused', stopped: 'Stopped' };

const Waveform = memo(function Waveform({ wave, window_s }) {
  const names = Object.keys(wave);
  const t1 = Math.max(...names.map((c) => wave[c].t.at(-1) ?? 0));
  const series = names.filter((c) => wave[c].t.length).map((c) => ({ id: c, label: c, color: COLORS[c] || 'var(--s1)', x: wave[c].t, y: wave[c].y, width: 1.1 }));
  if (!series.length) return null;
  return <LineChart height={260} xTitle="s" xDomain={[Math.max(0, t1 - window_s), Math.max(t1, window_s)]} fmtX={(v) => v.toFixed(1)} fmtY={(v) => num(v, 2)} series={series} />;
});

const Spectrum = memo(function Spectrum({ ana, fmax }) {
  const sp = ana.spectrum;
  const k = sp.f_hz.findIndex((v) => v > fmax);
  const n = k < 0 ? sp.f_hz.length : k;
  const peaks = ana.features[ana.detail_channel].peaks.filter((p) => p.frequency_hz <= fmax).slice(0, 4);
  return <LineChart height={240} xTitle="Hz" xDomain={[0, fmax]} fmtX={hzTick} fmtY={(v) => num(v, 2)}
    markers={peaks.map((p) => ({ x: p.frequency_hz, label: `${hz(p.frequency_hz)} Hz` }))}
    series={[{ id: 's', label: 'amplitude (g)', color: 'var(--s1)', x: sp.f_hz.slice(0, n), y: sp.amplitude.slice(0, n), width: 1.4 }]} />;
});

const Gram = memo(function Gram({ ana, fmax }) {
  const sg = ana.spectrogram;
  const k = sg.f_hz.findIndex((v) => v > fmax);
  const n = k < 0 ? sg.f_hz.length : k;
  const f = sg.f_hz.slice(0, n);
  return <Heatmap f={f} t={sg.t_s} z={sg.power_db.slice(0, n)} height={240} fmtF={hzTick}
    fTicks={[0, 1, 2, 3, 4].map((i) => (i * fmax) / 4).filter((v) => v <= f[f.length - 1])} fmtT={(v) => `${(v + ana.window.start_s).toFixed(1)}`} />;
});

function Side({ ana, state }) {
  const f = ana.features[ana.detail_channel];
  const s = state?.settings;
  const truth = ana.truth;
  return (
    <div className="stack">
      <div className="panel panel-pad">
        <div className="eyebrow" style={{ marginBottom: 8 }}>Simulated fault vs model prediction</div>
        <table className="data"><tbody>
          <tr><td>Injected (ground truth)</td><td className="num">{truth ? truth.label + (truth.fault === 'healthy' ? '' : ` · sev ${truth.severity.toFixed(2)}`) : 'unknown to the dashboard'}</td></tr>
          <tr><td>Model prediction</td><td className="num">{ana.classification.status === 'available' ? `${ana.classification.label} · ${Math.round(ana.classification.confidence * 100)}%` : '–'}</td></tr>
        </tbody></table>
        <div className="chart-caption">The injected fault is how the demo was set up; the prediction comes from the trained models. Agreement on simulated data is not evidence about real engines.</div>
      </div>
      <Classification c={ana.classification} />
      <div className="grid3" style={{ gridTemplateColumns: '1fr 1fr' }}>
        <Stat label="RMS" value={num(f.rms)} unit="g" />
        <Stat label="Peak-to-peak" value={num(f.peak_to_peak)} unit="g" />
        <Stat label="Crest factor" value={num(f.crest_factor)} />
        <Stat label="Kurtosis" value={num(f.kurtosis)} sub="excess" />
      </div>
      <div className="panel panel-pad">
        <div className="eyebrow" style={{ marginBottom: 8 }}>Live features · {ana.detail_channel}</div>
        <table className="data"><tbody>
          {[['Mean', f.mean], ['Std dev', f.std], ['Skewness', f.skewness], ['Spectral centroid (Hz)', f.spectral_centroid_hz]]
            .map(([k, v]) => <tr key={k}><td>{k}</td><td className="num">{num(v)}</td></tr>)}
        </tbody></table>
        <div className="eyebrow" style={{ margin: '12px 0 6px' }}>Dominant peaks</div>
        <table className="data"><tbody>
          {f.peaks.slice(0, 5).map((p) => <tr key={p.frequency_hz}><td>{hz(p.frequency_hz)} Hz</td><td className="num">{num(p.amplitude)} g</td></tr>)}
        </tbody></table>
        <div className="eyebrow" style={{ margin: '12px 0 6px' }}>Band energy</div>
        <HBars items={f.bands.map((b) => ({ label: `${hz(b.lo_hz)}–${hz(b.hi_hz)} Hz`, value: b.fraction ?? 0 }))} fmt={(v) => `${(v * 100).toFixed(1)}%`} />
      </div>
      {ana.orders && (
        <div className="panel panel-pad">
          <div className="eyebrow" style={{ marginBottom: 8 }}>Engine orders · {ana.orders.rpm} rpm</div>
          <table className="data"><tbody>
            {ana.orders.orders.map((o, i) => <tr key={o}><td>{o}×  ({hz(ana.orders.frequency_hz[i])} Hz)</td><td className="num">{num(ana.orders.amplitude[i])} g</td></tr>)}
          </tbody></table>
        </div>
      )}
      <div className="panel panel-pad">
        <div className="eyebrow" style={{ marginBottom: 8 }}>Current settings</div>
        <div className="note">
          {s ? `${s.fs / 1000} kHz · ${s.rpm} rpm · ${s.condition} · speed ${s.speed}× · seed ${s.seed}` : ''}<br />
          Window {ana.window.duration_s.toFixed(2)} s of {ana.window.target_s} s ({ana.window.samples.toLocaleString()} samples), {num(ana.window.start_s, 4)}–{num(ana.window.end_s, 4)} s.
        </div>
        {ana.warnings.length > 0 && <div className="vib-warn" style={{ marginTop: 8 }}>{ana.warnings.map((w) => <div key={w}>• {w}</div>)}</div>}
      </div>
    </div>
  );
}
